'use strict';
/**
 * The list of migrations this build expects to find applied.
 *
 * `prisma migrate deploy` is a CLI, and three of the four Postgres-connected
 * processes ship without it (#236). What every process CAN do is read
 * `_prisma_migrations` and compare it with the chain its own build was cut
 * from — if that chain is baked into `@bge/database` at generate time. This
 * writes that manifest next to the generated client, so it is regenerated,
 * fingerprinted and typechecked by exactly the machinery the client already
 * has.
 *
 * Names only. Prisma's own checksum column is left alone until its algorithm
 * is confirmed; a missing or extra NAME is what boot needs to decide between
 * "behind", "ahead" and "in sync".
 */
const fs = require('node:fs');
const path = require('node:path');

const MANIFEST_FILE = 'migrations-manifest.ts';

function generatedDir(workspaceRoot) {
  return path.join(workspaceRoot, 'libs', 'database', 'src', 'lib', 'generated');
}

function manifestPath(workspaceRoot) {
  return path.join(generatedDir(workspaceRoot), MANIFEST_FILE);
}

/**
 * Migration directory names in lexical order — Prisma applies them in that
 * order, and the timestamp prefix is what makes lexical and chronological
 * agree. A directory is a migration only if it carries `migration.sql`;
 * `migration_lock.toml` and anything else in the tree is not.
 */
function listMigrationNames(migrationsDir) {
  if (!fs.existsSync(migrationsDir)) {
    throw new Error(`migrations directory not found: ${migrationsDir}`);
  }

  return fs
    .readdirSync(migrationsDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && fs.existsSync(path.join(migrationsDir, entry.name, 'migration.sql')))
    .map((entry) => entry.name)
    .sort();
}

/** A single-quoted TypeScript string literal; only `\\` and `'` need escaping inside one. */
function quote(name) {
  return `'${name.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

function renderMigrationsManifest(names) {
  const body = names.length === 0 ? '[]' : `[\n${names.map((name) => `  ${quote(name)},`).join('\n')}\n]`;

  return [
    '// AUTO-GENERATED by libs/scripts/src/prisma-generate/migrations-manifest.js (database `generate` target).',
    '// Do not edit: the next `prisma generate` rewrites it from prisma/migrations/.',
    '',
    '/**',
    ' * Every migration in `prisma/migrations/` at the time this build was generated,',
    ' * in apply order. The boot sequence compares it with `_prisma_migrations` to',
    ' * decide whether the database is behind, ahead of, or in sync with this code',
    ' * (#236).',
    ' */',
    `export const MIGRATION_NAMES: readonly string[] = ${body};`,
    '',
  ].join('\n');
}

function writeMigrationsManifest(workspaceRoot) {
  const names = listMigrationNames(path.join(workspaceRoot, 'prisma', 'migrations'));
  const target = manifestPath(workspaceRoot);

  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, renderMigrationsManifest(names));

  return target;
}

module.exports = { MANIFEST_FILE, listMigrationNames, manifestPath, renderMigrationsManifest, writeMigrationsManifest };
