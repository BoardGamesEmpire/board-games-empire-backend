'use strict';
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const { getDMMF } = require('@prisma/get-dmmf');

const { deriveUnitIdColumns, renderUnitIdColumns, writeUnitIdColumns } = require('./unit-id-columns');

// Each kind of field the map must tell apart (#994): a foreign key to
// Household and one to User, each model's own `id`, a list relation, a text
// field, and a foreign key to User that references `email` rather than `id`,
// which holds an address, not a user id.
const FIXTURE_SCHEMA = `
datasource db {
  provider = "postgresql"
}

model Household {
  id          String   @id
  name        String
  createdBy   User     @relation("Created", fields: [createdById], references: [id])
  createdById String
  members     Member[]
}

model User {
  id          String      @id
  email       String      @unique
  households  Household[] @relation("Created")
  memberships Member[]
  aliases     Alias[]
}

model Member {
  id          String    @id
  householdId String
  household   Household @relation(fields: [householdId], references: [id])
  userId      String
  user        User      @relation(fields: [userId], references: [id])
  note        String
}

model Alias {
  id         String @id
  ownerEmail String
  owner      User   @relation(fields: [ownerEmail], references: [email])
}
`;

/** What the fixture must produce, written with every key and list in sorted order. */
const FIXTURE_COLUMNS = {
  Alias: { Household: [], User: [], relations: { owner: 'User' } },
  Household: { Household: ['id'], User: ['createdById'], relations: { createdBy: 'User', members: 'Member' } },
  Member: { Household: ['householdId'], User: ['userId'], relations: { household: 'Household', user: 'User' } },
  User: {
    Household: [],
    User: ['id'],
    relations: { aliases: 'Alias', households: 'Household', memberships: 'Member' },
  },
};

const REAL_WORKSPACE_ROOT = path.resolve(__dirname, '..', '..', '..', '..');

function fixtureDatamodel() {
  const result = getDMMF({ datamodel: [['schema.prisma', FIXTURE_SCHEMA]] });

  if (!result.datamodel) {
    throw new Error(`fixture schema does not parse: ${result.error?.message ?? result.reason}`);
  }

  return result.datamodel;
}

/** The object literal a rendered module assigns to UNIT_ID_COLUMNS. */
function parseRendered(source) {
  const literal = /export const UNIT_ID_COLUMNS: [^=]+= ([\s\S]*);\n$/.exec(source);
  expect(literal).not.toBeNull();

  return JSON.parse(literal[1]);
}

describe('unit-id columns (#994)', () => {
  describe('deriveUnitIdColumns', () => {
    it("finds each model's id columns and relation targets", () => {
      // Alias.ownerEmail is a foreign key to User, but to its email: it holds
      // no user id, so it must not count. Member.note holds no id at all.
      const columns = deriveUnitIdColumns(fixtureDatamodel());

      expect(columns).toEqual(FIXTURE_COLUMNS);
      // Sorted keys and lists keep the generated file stable across runs.
      expect(JSON.stringify(columns)).toBe(JSON.stringify(FIXTURE_COLUMNS));
    });
  });

  describe('renderUnitIdColumns', () => {
    it('writes a typed, deterministic module', () => {
      const columns = deriveUnitIdColumns(fixtureDatamodel());

      const source = renderUnitIdColumns(columns);

      const [first, second] = source.split('\n');
      expect(first).toMatch(/^\/\/ AUTO-GENERATED by libs\/scripts\/src\/prisma-generate\/unit-id-columns\.js /);
      expect(second).toMatch(/^\/\/ Do not edit/);
      expect(source).toContain('export interface ModelUnitIdColumns {');
      expect(source).toContain('  readonly Household: readonly string[];');
      expect(source).toContain('  readonly User: readonly string[];');
      expect(source).toContain('  readonly relations: Readonly<Record<string, string>>;');
      expect(source).toContain('export const UNIT_ID_COLUMNS: Readonly<Record<string, ModelUnitIdColumns>> = ');
      expect(parseRendered(source)).toEqual(FIXTURE_COLUMNS);
      expect(renderUnitIdColumns(deriveUnitIdColumns(fixtureDatamodel()))).toBe(source);
    });
  });

  describe('writeUnitIdColumns', () => {
    let workspaceRoot;

    beforeEach(() => {
      workspaceRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'bge-unit-id-columns-'));
    });

    afterEach(() => {
      fs.rmSync(workspaceRoot, { recursive: true, force: true });
    });

    it('reads the real schema', () => {
      // A copy of the real prisma/ tree, so the run writes into the temp
      // workspace and never into the checkout's generated client.
      fs.cpSync(path.join(REAL_WORKSPACE_ROOT, 'prisma'), path.join(workspaceRoot, 'prisma'), { recursive: true });

      const written = writeUnitIdColumns(workspaceRoot);

      expect(written).toBe(
        path.join(workspaceRoot, 'libs', 'database', 'src', 'lib', 'generated', 'unit-id-columns.ts'),
      );
      const columns = parseRendered(fs.readFileSync(written, 'utf8'));
      expect(columns.Event.Household).toContain('householdId');
      expect(columns.Event.Household).not.toContain('title');
      expect(columns.Event.relations.household).toBe('Household');
      // Its primary key is also its foreign key to Household.
      expect(columns.HouseholdSettings.Household).toContain('householdId');
      expect(columns.Household.User).toContain('createdById');
    });

    it('leaves out schema files under prisma/migrations', () => {
      fs.mkdirSync(path.join(workspaceRoot, 'prisma', 'migrations', '20260101000000_init'), { recursive: true });
      fs.writeFileSync(path.join(workspaceRoot, 'prisma', 'schema.prisma'), FIXTURE_SCHEMA);
      fs.writeFileSync(
        path.join(workspaceRoot, 'prisma', 'migrations', '20260101000000_init', 'stray.prisma'),
        'model {',
      );

      const written = writeUnitIdColumns(workspaceRoot);

      expect(parseRendered(fs.readFileSync(written, 'utf8'))).toEqual(FIXTURE_COLUMNS);
    });

    it('refuses a schema getDMMF cannot parse', () => {
      fs.mkdirSync(path.join(workspaceRoot, 'prisma'), { recursive: true });
      fs.writeFileSync(path.join(workspaceRoot, 'prisma', 'schema.prisma'), 'model {');

      expect(() => writeUnitIdColumns(workspaceRoot)).toThrow(/^unit-id columns: .*Error validating/s);
    });
  });
});
