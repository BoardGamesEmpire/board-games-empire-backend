'use strict';
/**
 * The columns that hold a household id or a user id, for each Prisma model.
 *
 * A household or a user may consent to a core permission for a plugin only
 * when its conditions hold every row to that unit's own id (#591). An
 * equality on the id binds only if the field holds that kind of id: a text
 * field set to a household's id would put any row with that text inside the
 * household's consent (#994). The schema already says which fields those are,
 * as foreign keys, so this reads them from it at generate time and writes them
 * beside the generated client. `bindsConsentUnit` reads the result. Nothing
 * reads the schema at runtime, so images ship neither it nor the parser.
 *
 * An id column is a foreign key to `Household.id` or `User.id`, or that
 * model's own `id`. A foreign key that references another column of User
 * (`email`, say) holds that column's value, not an id, so it does not count.
 * Every relation field is recorded with the model it points to, so a relation
 * filter can be judged against the related model's columns.
 */
const fs = require('node:fs');
const path = require('node:path');

const { listFiles } = require('./list-files');

const UNIT_ID_COLUMNS_FILE = 'unit-id-columns.ts';

/** The models whose ids a consent unit names. */
const UNIT_MODELS = ['Household', 'User'];

function generatedDir(workspaceRoot) {
  return path.join(workspaceRoot, 'libs', 'database', 'src', 'lib', 'generated');
}

/**
 * Every schema file Prisma reads, as `[relativePath, content]` pairs in path
 * order. The migrations directory holds no schema.
 */
function readSchemaFiles(workspaceRoot) {
  const schemaDir = path.join(workspaceRoot, 'prisma');
  const migrationsDir = path.join(schemaDir, 'migrations');

  return listFiles(schemaDir, (file) => file.endsWith('.prisma') && !file.startsWith(migrationsDir + path.sep)).map(
    (file) => [path.relative(workspaceRoot, file), fs.readFileSync(file, 'utf8')],
  );
}

/** A model's single-field primary key, or undefined for a composite or missing one. */
function idOf(model) {
  const ids = model.fields.filter((field) => field.isId);

  return ids.length === 1 ? ids[0].name : undefined;
}

const sortedUnique = (names) => [...new Set(names)].sort();

/**
 * For each model, by name: the scalar fields holding a Household id and a
 * User id, and each relation field's target model. Pure; takes
 * `getDMMF(...).datamodel`.
 */
function deriveUnitIdColumns(datamodel) {
  const models = new Map(datamodel.models.map((model) => [model.name, model]));
  const unitIds = new Map(UNIT_MODELS.map((name) => [name, models.has(name) ? idOf(models.get(name)) : undefined]));
  const columns = {};

  for (const model of [...datamodel.models].sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))) {
    const found = { Household: [], User: [] };
    const relations = {};

    if (unitIds.has(model.name) && unitIds.get(model.name) !== undefined) {
      found[model.name].push(unitIds.get(model.name));
    }

    for (const field of model.fields) {
      if (field.kind !== 'object') continue;

      relations[field.name] = field.type;

      const targetId = unitIds.get(field.type);
      const from = field.relationFromFields ?? [];
      const to = field.relationToFields ?? [];

      if (targetId !== undefined && from.length === 1 && to.length === 1 && to[0] === targetId) {
        found[field.type].push(from[0]);
      }
    }

    columns[model.name] = {
      Household: sortedUnique(found.Household),
      User: sortedUnique(found.User),
      relations: Object.fromEntries(
        Object.keys(relations)
          .sort()
          .map((name) => [name, relations[name]]),
      ),
    };
  }

  return columns;
}

function renderUnitIdColumns(columns) {
  return [
    '// AUTO-GENERATED by libs/scripts/src/prisma-generate/unit-id-columns.js (database `generate` target).',
    '// Do not edit: the next `prisma generate` rewrites it from the schema in prisma/.',
    '',
    '/**',
    ' * The fields of one model that hold a consent unit id, and where its',
    ' * relations lead. `bindsConsentUnit` accepts a unit id only on these',
    ' * fields (#994).',
    ' */',
    'export interface ModelUnitIdColumns {',
    "  /** Scalar fields holding a Household id: foreign keys to `Household.id`, and Household's own `id`. */",
    '  readonly Household: readonly string[];',
    "  /** Scalar fields holding a User id: foreign keys to `User.id`, and User's own `id`. */",
    '  readonly User: readonly string[];',
    '  /** Each relation field, and the model it points to. */',
    '  readonly relations: Readonly<Record<string, string>>;',
    '}',
    '',
    '/** Every Prisma model in the schema this build was generated from, by name. */',
    `export const UNIT_ID_COLUMNS: Readonly<Record<string, ModelUnitIdColumns>> = ${JSON.stringify(columns, null, 2)};`,
    '',
  ].join('\n');
}

function writeUnitIdColumns(workspaceRoot) {
  // Loaded here, not at the top: client-state.js reads this module's file
  // name on every generate run, including the "already current" path, which
  // must not load the parser.
  const { getDMMF } = require('@prisma/get-dmmf');
  const result = getDMMF({ datamodel: readSchemaFiles(workspaceRoot) });

  if (!result.datamodel) {
    throw new Error(`unit-id columns: ${result.error?.message ?? result.reason ?? 'getDMMF returned no datamodel'}`);
  }

  const target = path.join(generatedDir(workspaceRoot), UNIT_ID_COLUMNS_FILE);

  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, renderUnitIdColumns(deriveUnitIdColumns(result.datamodel)));

  return target;
}

module.exports = { UNIT_ID_COLUMNS_FILE, deriveUnitIdColumns, renderUnitIdColumns, writeUnitIdColumns };
