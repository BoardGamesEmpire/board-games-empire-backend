/**
 * Build-time version stamp (the `generate` target of `libs/common/version`,
 * #212, #712).
 *
 * Reads the workspace `package.json` version and writes it as a TypeScript
 * constant to `libs/common/version/src/lib/generated/bge-version.ts`. It is
 * the product's version: the api checks plugin manifest `bgeCompat` ranges
 * against it, and the DataGateways built in this repo report it on Ping.
 * Binding it to the transpiled code itself means no environment variable,
 * nothing for an operator to misconfigure, and the value can never disagree
 * with the artifact actually running.
 *
 * The semver gate lives HERE, at the earliest possible point: an invalid
 * workspace version fails the BUILD. Downstream, `validatePluginManifest`
 * throws on an invalid `bgeVersion` per plugin load, and the loader routes
 * that into quarantine — which force-disables plugins in the DB. Failing
 * the build makes that branch unreachable from this host.
 *
 * The write is idempotent — unchanged content is not rewritten — so watch
 * mode and Nx output hashing don't churn on every run.
 *
 * The output is gitignored (a build artifact, like the Prisma client and
 * proto-gateway codegen): fresh clones generate it via any target that
 * depends on `generate`, which is any typecheck, test or build of a project
 * that imports `@bge/version`.
 */
const { existsSync, mkdirSync, readFileSync, writeFileSync } = require('node:fs');
const { join } = require('node:path');
const { valid } = require('semver');

const workspaceRoot = join(__dirname, '..', '..', '..', '..');
const outDir = join(workspaceRoot, 'libs', 'common', 'version', 'src', 'lib', 'generated');
const outFile = join(outDir, 'bge-version.ts');

const packageJsonPath = join(workspaceRoot, 'package.json');
const { version } = JSON.parse(readFileSync(packageJsonPath, 'utf8'));

if (valid(version) === null) {
  console.error(
    `[generate-bge-version] workspace package.json version '${version}' is not valid semver — ` +
      'plugin bgeCompat evaluation requires a valid version, refusing to stamp it into the build.',
  );
  process.exit(1);
}

const content = `// AUTO-GENERATED by libs/scripts/src/bin/generate-bge-version.js (the \`generate\`
// target of libs/common/version). Do not edit. Gitignored build artifact,
// regenerated by any typecheck, test or build of a project that imports
// \`@bge/version\`.

/**
 * The product version, stamped at build time: the version plugin manifest
 * \`bgeCompat\` ranges are checked against (#59/#212), and the version the
 * DataGateways built in this repo report on Ping (#712). Distinct from the
 * BGE_VERSION deployment-identity env var reported by DeploymentInfoService.
 */
export const BGE_VERSION = '${version}';
`;

if (existsSync(outFile) && readFileSync(outFile, 'utf8') === content) {
  console.log(`[generate-bge-version] ${outFile} already at ${version}`);
} else {
  mkdirSync(outDir, { recursive: true });
  writeFileSync(outFile, content);
  console.log(`[generate-bge-version] stamped ${version} -> ${outFile}`);
}
